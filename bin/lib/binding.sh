# Matrix CLI — binding module (sourced by bin/matrix)

adapter_binding() {
    local target="$1"
    local json
    json="$(python3 "$MATRIX_DIR/adapters/_adapter_meta.py" binding --target="$target" 2>/dev/null)" || return 1
    [[ -z "$json" || "$json" == "null" ]] && return 1
    ADB_FILE="$(jq -r '.file // empty' <<<"$json")"
    ADB_BEGIN="$(jq -r '.begin_marker // empty' <<<"$json")"
    ADB_END="$(jq -r '.end_marker // empty' <<<"$json")"
    ADB_DOC_PATH="$(jq -r '.doc_path // empty' <<<"$json")"
    mapfile -t ADB_EXCLUDE < <(jq -r '.exclude_entries[]? // empty' <<<"$json")
    [[ -n "$ADB_FILE" && -n "$ADB_BEGIN" && -n "$ADB_END" ]]
}

MATRIX_EXCLUDE_BEGIN="# === MATRIX:EXCLUDE:BEGIN (managed by bin/matrix — do not hand-edit) ==="
MATRIX_EXCLUDE_END="# === MATRIX:EXCLUDE:END ==="

adapter_doc_path() {
    # Resolve the current adapter's own reference doc (binding.doc_path in
    # adapter.yaml) to an absolute path. Single owner for this lookup so
    # Python callers (session_audit.py) don't reimplement adapter.yaml
    # parsing — same "one bash owner" principle as resolve_scope()/scope.
    local target="${1:-devin}"
    adapter_binding "$target" || return 1
    [[ -n "$ADB_DOC_PATH" ]] || return 1
    printf '%s\n' "$MATRIX_DIR/$ADB_DOC_PATH"
}

path_is_bound() {
    local pp="$1" target="${2:-devin}"
    [[ -n "$pp" ]] || return 1
    local link="$pp/_brain"
    [[ -L "$link" ]] || return 1
    local rl; rl="$(readlink -f "$link" 2>/dev/null || true)"
    [[ "$rl" == "$BRAIN_DIR" ]] || return 1
    adapter_binding "$target" || return 1
    [[ -f "$pp/$ADB_FILE" ]] || return 1
    grep -qF "$ADB_BEGIN" "$pp/$ADB_FILE" && grep -qxF "$ADB_END" "$pp/$ADB_FILE"
}

is_bound() {
    local name="$1"
    local pp; pp="$(get_project_path "$name" 2>/dev/null)" || return 1
    [[ -z "$pp" ]] && return 1
    local target; target="$(registry_bound_target "$name")"
    [[ -n "$target" && "$target" != "null" ]] || target="devin"
    path_is_bound "$pp" "$target"
}

# --- Adapter-declared binding (non-probabilistic Neo activation) -----------
# Preamble source of truth: brain/data/activation-preamble.tmpl
matrix_block_tmp() {
    local target="${1:-devin}"
    adapter_binding "$target" || return 1
    local tmpl="$BRAIN_DIR/data/activation-preamble.tmpl"
    local tmp; tmp="$(mktemp)"
    local core; core="$(cat "$tmpl")"
    core="${core//\{\{CONTRACT_PATH\}\}/$MATRIX_DIR/AGENTS.md}"
    core="${core//\{\{NEO_AGENT_PATH\}\}/$BRAIN_DIR/agents/neo.md}"
    core="${core//\{\{ADAPTER_DOC_PATH\}\}/$MATRIX_DIR/$ADB_DOC_PATH}"
    {
        printf '%s\n' "$ADB_BEGIN (managed by \`bin/matrix select\` — do not hand-edit this block) -->"
        printf '%s\n\n' "This project is bound to the Matrix system (root: $MATRIX_DIR)."
        printf '%s' "$core"
        printf '\n'
        printf '%s\n' 'This block is regenerated by `bin/matrix select` / removed by `bin/matrix deselect` — do not edit it by hand; edit outside the markers instead.'
        printf '%s\n' "$ADB_END"
    } > "$tmp"
    echo "$tmp"
}

update_agents_local() {
    local pp="$1" target="${2:-devin}"
    adapter_binding "$target" || return 1
    local file="$pp/$ADB_FILE"
    local block; block="$(matrix_block_tmp "$target")" || return 1

    if [[ -f "$file" ]]; then
        if grep -qF "$ADB_BEGIN" "$file" && grep -qxF "$ADB_END" "$file"; then
            awk -v new="$block" -v begin="$ADB_BEGIN" -v end="$ADB_END" '
                index($0, begin) == 1 {
                    while ((getline line < new) > 0) print line
                    close(new)
                    inside=1
                    next
                }
                $0 == end { inside=0; next }
                !inside { print }
            ' "$file" > "$file.new" && mv "$file.new" "$file"
            log_success "Updated $ADB_FILE"
        else
            { echo ""; cat "$block"; } >> "$file"
            log_success "Appended Matrix block to $ADB_FILE"
        fi
    else
        mv "$block" "$file"
        log_success "Wrote $ADB_FILE"
    fi
    rm -f "$block"
}

cleanup_agents_local() {
    local ap="$1" target="${2:-devin}"
    adapter_binding "$target" || return 1
    local file="$ap/$ADB_FILE"
    [[ -f "$file" ]] || return 0

    if grep -qF "$ADB_BEGIN" "$file" && grep -qxF "$ADB_END" "$file"; then
        awk -v begin="$ADB_BEGIN" -v end="$ADB_END" '
            index($0, begin) == 1 { inside=1; next }
            $0 == end { inside=0; next }
            !inside { print }
        ' "$file" > "$file.new"

        if grep -q '[^[:space:]]' "$file.new"; then
            mv "$file.new" "$file"
            log_success "Removed Matrix block from $ADB_FILE"
        else
            rm -f "$file.new" "$file"
            log_success "Removed $ADB_FILE (empty after cleanup)"
        fi
    else
        log_warning "$ADB_FILE has no Matrix block; leaving untouched"
    fi
}

update_exclude() {
    local pp="$1" target="${2:-devin}"
    adapter_binding "$target" || return 1
    git -C "$pp" rev-parse --is-inside-work-tree >/dev/null 2>&1 || return 0
    local exf
    exf="$(git -C "$pp" rev-parse --git-path info/exclude)"
    [[ "$exf" != /* ]] && exf="$pp/$exf"
    local exdir
    exdir="$(dirname "$exf")"
    [[ -d "$exdir" ]] || mkdir -p "$exdir"
    local block changed=0 entry
    block="$(mktemp)"
    {
        printf '%s\n' "$MATRIX_EXCLUDE_BEGIN"
        for entry in "${ADB_EXCLUDE[@]}"; do
            printf '%s\n' "$entry"
        done
        printf '%s\n' "$MATRIX_EXCLUDE_END"
    } > "$block"
    if [[ -f "$exf" ]] && grep -qxF "$MATRIX_EXCLUDE_BEGIN" "$exf" && grep -qxF "$MATRIX_EXCLUDE_END" "$exf"; then
        awk -v new="$block" -v begin="$MATRIX_EXCLUDE_BEGIN" -v end="$MATRIX_EXCLUDE_END" '
            index($0, begin) == 1 {
                while ((getline line < new) > 0) print line
                close(new)
                inside=1
                next
            }
            $0 == end { inside=0; next }
            !inside { print }
        ' "$exf" > "$exf.new"
        if diff -q "$exf" "$exf.new" >/dev/null 2>&1; then
            rm -f "$exf.new"
        else
            mv "$exf.new" "$exf"
            changed=1
        fi
    else
        { echo ""; cat "$block"; } >> "$exf"
        changed=1
    fi
    rm -f "$block"
    [[ $changed -eq 1 ]] && log_success "Updated .git/info/exclude with Matrix exclude block"
    return 0
}

# cleanup_exclude <ap> <target>
# Remove the managed MATRIX:EXCLUDE block from .git/info/exclude.
# Never deletes the exclude file itself.
cleanup_exclude() {
    local ap="$1" target="${2:-devin}"
    adapter_binding "$target" || return 1
    git -C "$ap" rev-parse --is-inside-work-tree >/dev/null 2>&1 || return 0
    local exf
    exf="$(git -C "$ap" rev-parse --git-path info/exclude)"
    [[ "$exf" != /* ]] && exf="$ap/$exf"
    [[ -f "$exf" ]] || return 0
    if grep -qxF "$MATRIX_EXCLUDE_BEGIN" "$exf" && grep -qxF "$MATRIX_EXCLUDE_END" "$exf"; then
        awk -v begin="$MATRIX_EXCLUDE_BEGIN" -v end="$MATRIX_EXCLUDE_END" '
            index($0, begin) == 1 { inside=1; next }
            $0 == end { inside=0; next }
            !inside { print }
        ' "$exf" > "$exf.new" && mv "$exf.new" "$exf"
        log_success "Removed Matrix exclude block from .git/info/exclude"
    fi
    return 0
}

# exclude_leak_check <pp> <target> [ref]
# For each entry in ADB_EXCLUDE, checks if it is tracked in the given ref
# (default HEAD). Prints leaked entries one per line. Exit 0 always.
exclude_leak_check() {
    local pp="$1" target="$2" ref="${3:-HEAD}"
    adapter_binding "$target" || return 0
    git -C "$pp" rev-parse --is-inside-work-tree >/dev/null 2>&1 || return 0
    local entry
    for entry in "${ADB_EXCLUDE[@]}"; do
        if git -C "$pp" ls-tree -r --name-only "$ref" -- "$entry" 2>/dev/null | grep -q .; then
            printf '%s\n' "$entry"
        fi
    done
    return 0
}

exclude_audit() {
    local name="" all_branches=false arg
    for arg in "$@"; do
        case "$arg" in
            --all-branches) all_branches=true ;;
            --*) log_error "Unknown flag '$arg'"; return 1 ;;
            *) if [[ -z "$name" ]]; then name="$arg"; else log_error "Unexpected argument '$arg'"; return 1; fi ;;
        esac
    done
    [[ -n "$name" ]] || { log_error "Usage: matrix exclude audit <name> [--all-branches]"; return 1; }
    local pp; pp="$(get_project_path "$name" 2>/dev/null)" || { log_error "Project '$name' not found"; return 1; }
    [[ -d "$pp" ]] || { log_error "Path '$pp' does not exist"; return 1; }
    local target; target="$(registry_bound_target "$name")"
    [[ -n "$target" && "$target" != "null" ]] || target="devin"
    adapter_binding "$target" || { log_error "Cannot resolve adapter binding for target '$target'"; return 1; }

    if $all_branches; then
        local any_leak=false branch
        while IFS= read -r branch; do
            [[ -n "$branch" ]] || continue
            local leaked
            leaked="$(exclude_leak_check "$pp" "$target" "$branch")"
            if [[ -n "$leaked" ]]; then
                any_leak=true
                echo "[$branch] tracked leak: $(echo "$leaked" | tr '\n' ' ' | sed 's/ $//')"
            fi
        done < <(git -C "$pp" for-each-ref --format='%(refname:short)' refs/heads/ 2>/dev/null)
        $any_leak || echo "clean"
    else
        local leaked
        leaked="$(exclude_leak_check "$pp" "$target" HEAD)"
        if [[ -n "$leaked" ]]; then
            echo "tracked leak on current branch: $(echo "$leaked" | tr '\n' ' ' | sed 's/ $//')"
        else
            echo "clean"
        fi
    fi
}

exclude_fix() {
    local name="" do_fix=false arg
    for arg in "$@"; do
        case "$arg" in
            --fix) do_fix=true ;;
            --*) log_error "Unknown flag '$arg'"; return 1 ;;
            *) if [[ -z "$name" ]]; then name="$arg"; else log_error "Unexpected argument '$arg'"; return 1; fi ;;
        esac
    done
    [[ -n "$name" ]] || { log_error "Usage: matrix exclude fix <name> [--fix]"; return 1; }
    local pp; pp="$(get_project_path "$name" 2>/dev/null)" || { log_error "Project '$name' not found"; return 1; }
    [[ -d "$pp" ]] || { log_error "Path '$pp' does not exist"; return 1; }
    local target; target="$(registry_bound_target "$name")"
    [[ -n "$target" && "$target" != "null" ]] || target="devin"
    adapter_binding "$target" || { log_error "Cannot resolve adapter binding for target '$target'"; return 1; }

    local leaked
    leaked="$(exclude_leak_check "$pp" "$target" HEAD)"
    if [[ -z "$leaked" ]]; then
        log_success "No tracked leaks found for '$name'"
        return 0
    fi

    if ! $do_fix; then
        echo "tracked leak on current branch: $(echo "$leaked" | tr '\n' ' ' | sed 's/ $//')"
        log_warning "Usá 'matrix exclude fix $name --fix' para destrackear (staged, sin commit)"
        return 0
    fi

    local entry
    while IFS= read -r entry; do
        [[ -n "$entry" ]] || continue
        git -C "$pp" rm -r --cached -- "$entry" 2>/dev/null || true
        log_info "Destrackeado: $entry"
    done <<< "$leaked"
    update_exclude "$pp" "$target"
    log_success "Destrackeado + bloque exclude sincronizado. NO se comiteó nada."
}

exclude_cmd() {
    case "${1:-}" in
        audit) shift; exclude_audit "$@" ;;
        fix)   shift; exclude_fix "$@" ;;
        *)     log_error "Usage: matrix exclude audit <name> [--all-branches] | fix <name> [--fix]"; return 1 ;;
    esac
}

# ensure_project_output_dirs <name>
# Creates this bound project's own artifact subtree under this repo's
# brain/output/<name>/{architecture,plans,research,eval}/, if missing.
# Idempotent — same pattern as update_agents_local()/update_exclude().
ensure_project_output_dirs() {
    local name="$1"
    [[ -n "$name" ]] || return 1
    local base="$BRAIN_DIR/output/$name"
    local sub created=0
    for sub in architecture plans research eval; do
        if [[ ! -d "$base/$sub" ]]; then
            mkdir -p "$base/$sub"
            created=1
        fi
    done
    [[ $created -eq 1 ]] && log_success "Created brain/output/$name/{architecture,plans,research,eval}/"
    return 0
}

select_project() {
    local name="${1:-}" target="devin" arg
    shift || true
    for arg in "$@"; do
        case "$arg" in
            --target=*) target="${arg#*=}" ;;
            --*) log_error "Unknown flag '$arg'"; return 1 ;;
            *) log_error "Unexpected argument '$arg'"; return 1 ;;
        esac
    done
    [[ -n "$name" ]] || { log_error "Usage: matrix select <name> [--target=<cli>]"; return 1; }
    is_workspace_target "$name" && { log_error "'$name' is a reserved name (the Matrix workspace itself) — choose another"; return 1; }
    adapter_binding "$target" || { log_warning "Trainman: no adapter binding (not implemented yet for '$target')."; return 1; }
    local p t pp
    p="$(registry_path "$name")"
    t="$(registry_type "$name")"
    [[ -z "$p" || "$p" == "null" ]] && { log_error "Project '$name' not found"; return 1; }
    if [[ "$t" == "remote" ]]; then
        pp="$CLIENTS_DIR/$name"
        [[ -d "$pp" ]] || { log_info "Cloning '$name'..."; mkdir -p "$CLIENTS_DIR"; git clone "$p" "$pp"; }
    else
        pp="$(to_abs_path "$p")"; pp="${pp%/}"
    fi
    [[ -d "$pp" ]] || { log_error "Path '$pp' does not exist"; return 1; }
    local pp_real; pp_real="$(readlink -f "$pp" 2>/dev/null || true)"
    local matrix_real; matrix_real="$(readlink -f "$MATRIX_DIR" 2>/dev/null || true)"
    [[ "$pp_real" == "$matrix_real" ]] && { log_error "Cannot bind the Matrix root itself as a project"; return 1; }
    local link="$pp/_brain"
    if [[ -L "$link" ]]; then
        local current; current="$(readlink -f "$link" 2>/dev/null || true)"
        if [[ "$current" != "$BRAIN_DIR" ]]; then
            rm "$link"
        fi
    fi
    [[ -e "$link" && ! -L "$link" ]] && { log_error "'_brain' exists and is not a symlink"; return 1; }
    [[ -L "$link" ]] || ln -sf "$BRAIN_DIR" "$link"
    update_agents_local "$pp" "$target"
    update_exclude "$pp" "$target"
    ensure_project_output_dirs "$name"
    set_registry_bound_target "$name" "$target"
    warm_project_entry "$name" "$pp" "quiet"
    link_append "project:select" "$name" "$pp"
    log_success "Selected project '$name' (symlink: $link)"
}

deselect_project() {
    local name="" target="" arg
    for arg in "$@"; do
        case "$arg" in
            --target=*) target="${arg#*=}" ;;
            --*) log_error "Unknown flag '$arg'"; return 1 ;;
            *) if [[ -z "$name" ]]; then name="$arg"; else log_error "Unexpected argument '$arg'"; return 1; fi ;;
        esac
    done
    if [[ -z "$name" ]]; then
        log_error "Usage: matrix deselect <name> [--target=<cli>]"
        return 1
    fi
    if [[ -z "$target" ]]; then
        target="$(registry_bound_target "$name")"
        [[ -n "$target" && "$target" != "null" ]] || target="devin"
    fi
    adapter_binding "$target" || { log_warning "Trainman: no adapter binding (not implemented yet for '$target')."; return 1; }
    local ap; ap="$(get_project_path "$name" 2>/dev/null)" || { log_warning "Project '$name' not found"; return 0; }
    if ! path_is_bound "$ap" "$target"; then
        log_warning "Project '$name' is not bound"
        return 0
    fi
    cleanup_agents_local "$ap" "$target"
    cleanup_exclude "$ap" "$target"
    [[ -n "$ap" && -L "$ap/_brain" ]] && rm "$ap/_brain"
    link_append "project:deselect" "$name" ""
    log_success "Deselected '$name'"
}

# --- Multi-project warm set -------------------------------------------------
# warm_project_entry <name> <path> [quiet]
# Shared, idempotent core: ensures <name> is a member of the warm set with
# the given (already-resolved) path. Used by both `matrix work` (resolves
# the path itself from the registry) and `select_project` (already has the
# resolved path, including the local clone dir for `remote` projects — never
# re-resolve from the registry there, or a `remote` project's warm entry
# would end up holding the remote URL instead of its local checkout path).
